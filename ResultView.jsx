import { CheckCircle2, CircleDashed, Lightbulb, RotateCcw } from 'lucide-react'
import { percent } from '../utils/format.js'
import ProfileBars from './ProfileBars.jsx'
import Disclaimer from './Disclaimer.jsx'

export default function ResultView({ result, values, onReset }) {
  const placed = result.prediction === 'Placed'
  const label = placed ? 'PLACED' : 'NOT PLACED'
  const Icon = placed ? CheckCircle2 : CircleDashed

  return (
    <div className="container-page animate-rise pb-8 pt-12 sm:pt-16">
      <h1 className="text-3xl font-extrabold tracking-tight sm:text-5xl">Your Profile Has Been Analyzed</h1>

      <section aria-labelledby="result-heading" className="mt-8 rounded-3xl bg-navy p-6 text-cream sm:p-10">
        <h2 id="result-heading" className="sr-only">Prediction result</h2>
        <div className="flex items-center gap-4">
          <Icon className="h-10 w-10 shrink-0" aria-hidden="true" />
          <p className="text-4xl font-extrabold tracking-tight sm:text-6xl">{label}</p>
        </div>
        <p className="mt-4 max-w-2xl text-lg leading-relaxed text-cream/90">
          Based on patterns learned from the historical dataset, the model classified this profile as {placed ? 'Placed' : 'Not Placed'}.
        </p>

        <dl className="mt-8 grid gap-4 sm:grid-cols-2">
          <div className="rounded-2xl bg-cream/10 p-5">
            <dt className="text-xs font-bold tracking-wide text-cream/80">Model probability</dt>
            <dd className="mt-1 text-4xl font-extrabold tabular-nums">{percent(result.probability, 0)}</dd>
          </div>
          <div className="rounded-2xl bg-cream/10 p-5">
            <dt className="text-xs font-bold tracking-wide text-cream/80">Model test accuracy</dt>
            <dd className="mt-1 text-4xl font-extrabold tabular-nums">{percent(result.model_accuracy)}</dd>
          </div>
        </dl>
        <p className="mt-5 max-w-3xl text-sm leading-relaxed text-cream/80">
          This probability represents the model&rsquo;s estimated probability for the predicted class based on the patterns learned from the training data. It is not a guarantee of real-world employment.
        </p>
      </section>

      <div className="mt-8 grid gap-6 lg:grid-cols-2">
        <section className="card" aria-labelledby="overview-heading">
          <h2 id="overview-heading" className="mb-5 text-xl font-extrabold">Profile Overview</h2>
          <ProfileBars values={values} />
        </section>

        <section className="card" aria-labelledby="guidance-heading">
          <h2 id="guidance-heading" className="text-xl font-extrabold">Career Guidance</h2>
          <h3 className="mt-1 text-sm font-bold text-brown">Suggested Focus Areas</h3>
          {result.focus_areas.length ? (
            <ol className="mt-5 space-y-4">
              {result.focus_areas.map((area, i) => (
                <li key={area.title} className="flex gap-3 rounded-xl bg-cream-light p-4">
                  <Lightbulb className="mt-0.5 h-5 w-5 shrink-0 text-brown" aria-hidden="true" />
                  <div>
                    <p className="font-bold">Possible focus area {i + 1}: {area.title}</p>
                    <p className="mt-1 text-sm leading-relaxed text-navy-80">{area.suggestion}</p>
                  </div>
                </li>
              ))}
            </ol>
          ) : (
            <p className="mt-5 text-sm leading-relaxed text-navy-80">None of the simple profile rules flagged a focus area. Continuing to build projects, certifications and interview practice may still help strengthen your profile.</p>
          )}
          <p className="mt-5 text-xs leading-relaxed text-navy-80">
            These suggestions come from fixed, rule-based checks on the values you entered, ordered by simple severity rules. They were not generated by the machine-learning model, and no single factor determines placement.
          </p>
        </section>
      </div>

      <div className="mt-8 flex flex-wrap gap-3">
        <button type="button" className="btn-secondary" onClick={onReset}><RotateCcw size={16} aria-hidden="true" /> Edit Profile</button>
      </div>
      <Disclaimer className="mt-8" />
    </div>
  )
}
